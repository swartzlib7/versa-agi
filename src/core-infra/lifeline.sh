  echo "${CONVERSATION_CONTEXT}" > "${CONVO_FILE}"
  chmod 644 "${SYSTEM_FILE}" "${WAKE_FILE}" "${TASKS_FILE}" "${CONVO_FILE}"
  # Persist context prompt for dashboard/audit visibility.
